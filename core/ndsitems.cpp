template <size_t N> int find(const Entry (&t)[N], uint16_t item) {
    size_t lo = 0, hi = N;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (t[mid].item < item) lo = mid + 1;
        else hi = mid;
    }
    return (lo < N && t[lo].item == item) ? t[lo].pouch : -1;
}
