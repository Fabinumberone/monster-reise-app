int ndsTravelPouch(NDSGame g, uint16_t item) {
    switch (g) {
    case NDSGame::DP: return find(kDP, item);
    case NDSGame::Pt: return find(kPt, item);
    case NDSGame::HGSS: return find(kHGSS, item);
    default: return find(kBW, item);
    }
}

